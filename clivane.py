# LIST
# --------------------------------------------------------------------------

def cmd_list(pkg_dir):
    manifest = pkg_manifest(pkg_dir)
    files = []
    for root, dirs, names in os.walk(pkg_dir):
        dirs.sort()
        for n in sorted(names):
            files.append(os.path.relpath(os.path.join(root, n), pkg_dir))
    return manifest, files


